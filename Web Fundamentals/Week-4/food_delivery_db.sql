CREATE INDEX idx_delivery_assignments_order_assigned_at
    ON delivery_assignments(order_id, assigned_at);
CREATE INDEX idx_delivery_assignments_partner_assigned_at
    ON delivery_assignments(partner_id, assigned_at);
-- A single order can have only one current assignment at a time.
CREATE UNIQUE INDEX uq_delivery_assignments_one_active_per_order
    ON delivery_assignments(order_id)
