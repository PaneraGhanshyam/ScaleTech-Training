    price DECIMAL(12,2) NOT NULL,
    is_vegetarian BOOLEAN NOT NULL DEFAULT FALSE,
    is_available_for_order BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_menu_items_menu
        FOREIGN KEY (menu_id) REFERENCES menus(menu_id),
    CONSTRAINT chk_menu_item_price CHECK (price >= 0),
    CONSTRAINT uq_menu_item_name UNIQUE (menu_id, item_name)
);

-- ============================================================
-- 8. DELIVERY PARTNERS
-- ============================================================

CREATE TABLE delivery_partners (
    partner_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(15) NOT NULL UNIQUE,
    email VARCHAR(255) UNIQUE,
    vehicle_type vehicle_type NOT NULL,
    vehicle_model VARCHAR(100),
    vehicle_registration_number VARCHAR(30) UNIQUE,
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    is_available_for_delivery BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    last_known_latitude DECIMAL(10,7),
    last_known_longitude DECIMAL(10,7),
    last_location_updated_at TIMESTAMPTZ,
    total_deliveries INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_partner_latitude CHECK (
        last_known_latitude IS NULL OR last_known_latitude BETWEEN -90 AND 90
    ),
    CONSTRAINT chk_partner_longitude CHECK (
        last_known_longitude IS NULL OR last_known_longitude BETWEEN -180 AND 180
    ),
    CONSTRAINT chk_partner_total_deliveries CHECK (total_deliveries >= 0)
);

-- ============================================================
-- 9. ORDERS
-- The delivery destination is stored as a JSONB snapshot.
-- ============================================================

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    restaurant_id BIGINT NOT NULL,
    selected_address_id BIGINT,
    delivery_address_snapshot JSONB NOT NULL,
    subtotal DECIMAL(12,2) NOT NULL,
    delivery_fee DECIMAL(12,2) NOT NULL DEFAULT 0,
    tax_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    discount_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    total_amount DECIMAL(12,2) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'INR',
    status order_status NOT NULL DEFAULT 'placed',
    special_instructions TEXT,
    cancellation_reason TEXT,
    placed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    confirmed_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    delivery_address_changed_at TIMESTAMPTZ,
    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    CONSTRAINT fk_orders_restaurant
        FOREIGN KEY (restaurant_id) REFERENCES restaurants(restaurant_id),
    CONSTRAINT fk_orders_selected_address
        FOREIGN KEY (selected_address_id) REFERENCES addresses(address_id) ON DELETE SET NULL,
    CONSTRAINT chk_order_subtotal CHECK (subtotal >= 0),
    CONSTRAINT chk_order_delivery_fee CHECK (delivery_fee >= 0),
    CONSTRAINT chk_order_tax CHECK (tax_amount >= 0),
    CONSTRAINT chk_order_discount CHECK (discount_amount >= 0),
    CONSTRAINT chk_order_total_nonnegative CHECK (total_amount >= 0),
    CONSTRAINT chk_order_total CHECK (
        total_amount = subtotal + delivery_fee + tax_amount - discount_amount
    ),
    CONSTRAINT chk_order_discount_not_above_subtotal CHECK (discount_amount <= subtotal),
    -- Required address properties must exist as non-empty JSON strings.
    CONSTRAINT chk_delivery_address_snapshot CHECK (
        jsonb_typeof(delivery_address_snapshot) = 'object'
        AND jsonb_typeof(delivery_address_snapshot -> 'recipient_name') = 'string'
        AND NULLIF(BTRIM(delivery_address_snapshot ->> 'recipient_name'), '') IS NOT NULL
        AND jsonb_typeof(delivery_address_snapshot -> 'recipient_phone') = 'string'
        AND NULLIF(BTRIM(delivery_address_snapshot ->> 'recipient_phone'), '') IS NOT NULL
        AND jsonb_typeof(delivery_address_snapshot -> 'address_line') = 'string'
        AND NULLIF(BTRIM(delivery_address_snapshot ->> 'address_line'), '') IS NOT NULL
        AND jsonb_typeof(delivery_address_snapshot -> 'city') = 'string'
        AND NULLIF(BTRIM(delivery_address_snapshot ->> 'city'), '') IS NOT NULL
        AND jsonb_typeof(delivery_address_snapshot -> 'state') = 'string'
        AND NULLIF(BTRIM(delivery_address_snapshot ->> 'state'), '') IS NOT NULL
        AND jsonb_typeof(delivery_address_snapshot -> 'pincode') = 'string'
        AND NULLIF(BTRIM(delivery_address_snapshot ->> 'pincode'), '') IS NOT NULL
        AND (
            NOT (delivery_address_snapshot ? 'landmark')
            OR delivery_address_snapshot -> 'landmark' = 'null'::jsonb
            OR jsonb_typeof(delivery_address_snapshot -> 'landmark') = 'string'
        )
    )
);

CREATE INDEX idx_orders_customer_placed_at ON orders(customer_id, placed_at);
CREATE INDEX idx_orders_restaurant_placed_at ON orders(restaurant_id, placed_at);
CREATE INDEX idx_orders_status ON orders(status);
CREATE INDEX idx_orders_selected_address ON orders(selected_address_id);

